import type { NextConfig } from "next";

const isDev = process.env.NODE_ENV !== "production";

// Everything the site loads is its own, apart from Cloudflare Web Analytics (its beacon script, which reports back to
// cloudflareinsights.com): fonts are self-hosted by next/font, images and videos sit in /public, and the site's own
// fetch is /api/spotify. 'unsafe-inline' for scripts covers the small <head> scripts in layout.tsx, Next's own inline
// data and Cloudflare's bot check (served from /cdn-cgi on this origin); a nonce would make every page dynamic.
// 'unsafe-eval' is only for React's dev tooling.
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline' https://static.cloudflareinsights.com${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "media-src 'self'",
  `connect-src 'self' https://cloudflareinsights.com${isDev ? " ws:" : ""}`,
  "frame-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  ...(isDev ? [] : ["upgrade-insecure-requests"]),
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  // Two years, subdomains included. Not "preload": that's a separate opt-in that's slow to undo.
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
];

const nextConfig: NextConfig = {
  // <ViewTransition> (template.tsx) needs no flag since Next 16.3; it fades between pages on client-side navigation.

  // No "X-Powered-By: Next.js": it tells a scanner what to try, and nothing else needs it.
  poweredByHeader: false,

  // Cloudflare has no Next image optimizer here: /_next/image only passed the original file through, at full size.
  // Images are served as they are, so they're made small up front (scripts/make-captures.mjs, make-thumbs.mjs).
  images: { unoptimized: true },

  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },

  // /favicon.ico is what crawlers and older browsers ask for; app/favicon/route.ts makes the image.
  async rewrites() {
    return [{ source: "/favicon.ico", destination: "/favicon" }];
  },

  // Short links to share. Kept here so they work on any host.
  async redirects() {
    return [
      // The short link from the DesktopBuddy launch story, easy to type on a PC after seeing it on a phone.
      // Temporary (307) rather than permanent, so it's free to point somewhere else later.
      {
        source: "/buddy",
        destination: "/blimo",
        permanent: false,
      },
      // DesktopBuddy was renamed Blimo in 1.2, and its page moved with it. Permanent, so old links and
      // search results follow.
      {
        source: "/desktopbuddy",
        destination: "/blimo",
        permanent: true,
      },
      // iOS and some crawlers ask for these fixed names; the icon itself is generated by app/apple-icon.tsx.
      { source: "/apple-touch-icon.png", destination: "/apple-icon", permanent: false },
      { source: "/apple-touch-icon-precomposed.png", destination: "/apple-icon", permanent: false },
      // The résumé was renamed when it was rewritten; the old file is gone, so links to it still land.
      {
        source: "/resume/Jaineel_Khatri_Professionalv2.pdf",
        destination: "/resume/Jaineel_Khatri_Resume.pdf",
        permanent: true,
      },
    ];
  },
};

export default nextConfig;

// Hooks Cloudflare bindings into `next dev` so the Workers runtime can be
// exercised locally. No-op outside of dev — safe to leave in place when
// building for Vercel.
import { initOpenNextCloudflareForDev } from "@opennextjs/cloudflare";
initOpenNextCloudflareForDev();
