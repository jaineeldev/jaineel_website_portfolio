// Crops of the real captures for the share card (src/app/opengraph-image.tsx), 2x the size they're drawn at.
// They're written as data URIs into src/lib/og/assets.ts, so the card needs no file access wherever it renders
// (dev, build, or the Cloudflare worker). Usage: node scripts/make-og-assets.mjs
// Re-run when a capture changes, and commit the output.
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { captures, renderCapture, toDataUri } from "./lib/captures.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// The still card shows three of them.
const shown = ["blimo", "velo", "hawthorne"];

let out = `// Generated by scripts/make-og-assets.mjs. Don't edit by hand.\n`;
for (const capture of captures.filter((c) => shown.includes(c.name))) {
  const rendered = await renderCapture(capture);
  out += `export const ${capture.name} = "${toDataUri(rendered)}";\n`;
  console.log(capture.name.padEnd(12), `${(rendered.bytes.length / 1024).toFixed(0)} KB`);
}
await writeFile(resolve(root, "src/lib/og/assets.ts"), out);
